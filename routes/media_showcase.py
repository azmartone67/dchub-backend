"""
media_showcase.py — DC Hub Media auto-showcase (2026-06-30).
=============================================================

WHY
---
An external AI (Grok), handed DC Hub's tools, produced a sharper data showcase
than DC Hub's own media machine — BUT it hallucinated: it claimed ERCOT is "77%
data-center share" (real: 52.7%), "317 DCPI markets" (real: 311), and "4x YoY"
(not in the data). The existing media machine, meanwhile, is data-signal-driven,
contracting, and has no way to publish a compelling market-pulse or a milestone.

This module is the fix: produce the Grok-style, data-rich showcase content the
machine SHOULD write — but COMPELLING **and** VERIFIED. The differentiator vs a
raw LLM (Grok) is structural:

  · Every number is PULLED LIVE from DC Hub's own endpoints (gather_facts), never
    generated by a model. The composer interpolates verified figures into a
    punchy template — so it cannot hallucinate a 77% that's really 53%.
  · A numeric FACT-CHECK gate (_factcheck) scans the rendered post and rejects any
    number that isn't traceable to a gathered fact — a hard guarantee that the
    "compelling" copy never drifts from the truth.

ROUTES (admin-gated):
  GET  /api/v1/admin/media/showcase/preview?kind=market_pulse|milestone
       → generate + return the post + the verified facts (NO publish)
  POST /api/v1/admin/media/showcase/publish  {kind, [platform, detail]}
       → generate, fact-check, and publish via the existing LinkedIn poster
         (gated by can-publish + the content-quality floor). Never auto-fires;
         a human/cron triggers it.

Kill switch: MEDIA_SHOWCASE_DISABLED=1.
"""
