"""Guards for recipe_lifecycle.py + the v4 report metric it feeds.

Perplexity round-5 (2026-07-30): recipe lifecycle becomes a first-class fact
(started/completed rows in recipe_executions) instead of an inference over
tool-call rows. The rules pinned here are the ones that made the schema worth
building — and the ones this repo has paid for before:

  1. the identity key is the EXECUTION ID, never session_id (rotates per
     connection, ~1.2 calls/session — keying on it was the exact defect this
     schema exists to avoid);
  2. lifecycle events must never become tool-call rows (they would inflate
     the episode metrics they replace) — the track dispatch runs BEFORE the
     tool check and before any call-table write;
  3. every SQL string that executes WITH bound params is emulated through
     psycopg2 substitution (a stray literal % eats an argument — the
     2026-07-17 /api/v1/map outage class);
  4. abandonment is DERIVED at read time from a missing completion, never
     written by inference;
  5. the rendered migration on disk matches the module (LIVE≠repo-DDL class)
     — hand-editing either drifts the other.

No DB, no network, no Flask app: fake cursors capture SQL + params.
"""
import json
import re
from pathlib import Path

import pytest

rl = pytest.importorskip("recipe_lifecycle")
asr = pytest.importorskip("routes.agent_success_report")
dl = pytest.importorskip("mcp_calls_deloop")

ROOT = Path(__file__).resolve().parent.parent


class _Cur:
    def __init__(self):
        self.executed = []

    def execute(self, sql, params=None):
        self.executed.append((sql, params))

    def __enter__(self):
        return self

    def __exit__(self, *a):
        return False


class _Conn:
    def __init__(self):
        self.cur = _Cur()

    def cursor(self):
        return self.cur


def _emulate(sql, params):
    """psycopg2-style substitution over the exact SQL we execute. The raise,
    if any, IS the assertion — it is what production would do. Returns the
    substituted text so callers can assert every arg landed."""
    sentinels = tuple(f"__ARG{i}__" for i in range(len(params)))
    out = sql % sentinels
    for s in sentinels:
        assert s in out, f"an argument never bound: {s}"
    return out


# ── rule 5: DDL owned by the module, migration derived ─────────────────────

def test_ddl_shape_and_identity_contract():
    ddl = rl.TABLE_DDL
    assert "CREATE TABLE IF NOT EXISTS recipe_executions" in ddl
    assert "recipe_execution_id TEXT PRIMARY KEY" in ddl
    # session_id present for forensics — but NEVER the key (rule 1). The DDL
    # has exactly one PRIMARY KEY and the line above pins whose it is.
    assert "session_id" in ddl
    assert ddl.count("PRIMARY KEY") == 1
    assert "started_at          TIMESTAMPTZ NOT NULL" in ddl
    for outcome in rl.VALID_OUTCOMES:
        assert f"'{outcome}'" in ddl, f"outcome CHECK missing {outcome!r}"
    # CREATE-only: the apply workflow refuses destructive verbs, so the
    # module must never render one.
    for stmt in rl.all_ddl_statements():
        assert not re.search(r"^\s*(DROP|DELETE|TRUNCATE|ALTER|GRANT)\b",
                             stmt, re.I | re.M), f"destructive verb in: {stmt[:80]}"


