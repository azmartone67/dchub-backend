# ── writer validation: refuse, never coerce ────────────────────────────────

def test_record_refuses_bad_payloads():
    conn = _Conn()
    assert rl.record_lifecycle_event(None, {})[0] is False
    ok, err = rl.record_lifecycle_event(conn, {"phase": "started"})
    assert not ok and "recipe_execution_id" in err
    ok, err = rl.record_lifecycle_event(
        conn, {"recipe_execution_id": "x", "phase": "resumed"})
    assert not ok and "phase" in err
    # A mislabeled outcome is worse than a dropped event — refused outright,
    # so the started row stays and honestly reads as abandoned.
    ok, err = rl.record_lifecycle_event(
        conn, {"recipe_execution_id": "x", "phase": "completed",
               "outcome": "ok"})
    assert not ok and "outcome" in err
    assert conn.cur.executed == [], "a refused payload must write nothing"


def test_started_insert_is_idempotent_and_binds():
    conn = _Conn()
    ok, err = rl.record_lifecycle_event(conn, {
        "recipe_execution_id": "11111111-2222-3333-4444-555555555555",
        "phase": "started", "source": "execute_plan",
        "intent": "rank markets for a 200 MW AI campus",
        "intent_class": "market_ranking",
        "api_key": "dch_live_abc", "session_id": "sid-1",
        "platform": "perplexity", "user_agent": "node",
        "started_at": "2026-07-30T10:00:00Z",
    })
    assert ok and err is None
    (sql, params), = conn.cur.executed
    assert "ON CONFLICT (recipe_execution_id) DO NOTHING" in sql, \
        "a re-delivered started event must never duplicate or overwrite"
    out = _emulate(sql, params)
    assert "__ARG0__" in out  # the execution id bound first
    assert params[0] == "11111111-2222-3333-4444-555555555555"


def test_completed_upsert_finalizes_but_never_rewrites_identity():
    """Completion is an upsert so a LOST started event still yields a full
    row — but on conflict, only terminal fields update: the started row's
    identity and started_at win (completion finalizes; it never rewrites who
    started the recipe or when)."""
    conn = _Conn()
    ok, err = rl.record_lifecycle_event(conn, {
        "recipe_execution_id": "abc", "phase": "completed",
        "outcome": "completed", "started_at": "2026-07-30T10:00:00Z",
        "completed_at": "2026-07-30T10:00:21Z", "duration_ms": 21000,
        "steps_planned": 4,
        "status_counts": {"executed": 2, "gated_preview": 1,
                          "skipped_meta": 1, "skipped_unresolved": 1},
    })
    assert ok and err is None
    (sql, params), = conn.cur.executed
    assert "ON CONFLICT (recipe_execution_id) DO UPDATE SET" in sql
    set_clause = sql.split("DO UPDATE SET", 1)[1]
    for terminal in ("completed_at", "outcome", "duration_ms", "status_counts"):
        assert terminal in set_clause
    for frozen in ("api_key", "session_id", "platform", "user_agent",
                   "ip_address", "started_at", "intent"):
        assert not re.search(rf"^\s*{frozen}\s*=", set_clause, re.M), \
            f"completion must not rewrite {frozen} on an existing row"
    _emulate(sql, params)
    # steps derived from status_counts — skipped folds both skip kinds.
    assert params[-7:-1] == (4, 2, 1, 0, 0, 2)
    assert json.loads(params[-1])["executed"] == 2


def test_writer_sql_has_no_stray_percent():
    """Both writers always run WITH params — every % must be a %s."""
    for sql in (rl._INSERT_STARTED, rl._UPSERT_COMPLETED):
        assert sql.count("%") == sql.count("%s"), \
            "a literal % in a with-params query eats an argument (map-outage class)"


# ── rule 2: the track dispatch must precede every call-table write ─────────

def test_track_dispatch_runs_before_the_call_tables():
    """Textual placement pin over flask_mcp_endpoints.track_tool_call: the
    recipe_lifecycle dispatch (the CODE branch, not a comment) must sit
    before the missing-tool return and before both call-table INSERTs, so a
    lifecycle event can never be logged as a phantom tool call."""
    src = (ROOT / "flask_mcp_endpoints.py").read_text()
    h = src.index("def track_tool_call")
    dispatch = src.index('== "recipe_lifecycle"', h)
    record = src.index("record_lifecycle_event(_rl_conn, body)", h)
    missing_tool = src.index('"missing tool"', h)
    call_log = src.index("INSERT INTO mcp_call_log", h)
    legacy = src.index("INSERT INTO mcp_tool_calls", h)
    assert dispatch < missing_tool, "dispatch must precede the tool check"
    assert record < missing_tool
    assert dispatch < call_log and dispatch < legacy
    # skew-safety is the missing-tool return itself: the gateway payload
    # carries no `tool`, so a backend without the dispatch drops it there.


