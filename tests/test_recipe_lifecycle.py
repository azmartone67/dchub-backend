def test_report_metric_sql_binds_and_carries_exclusions():
    """Same emulation + population discipline as the second-recipe query:
    4 placeholders, synthetic + crawler exclusions from the shared modules
    (never a third hand-kept list), regex form only next to params."""
    sql = asr._recipe_lifecycle_sql()
    assert "recipe_executions" in sql
    assert "mcp_call_log" not in sql and "mcp_tool_calls" not in sql
    assert dl.internal_tag_regex_predicate("platform") in sql
    assert dl.real_ua_predicate("user_agent") in sql
    assert "ILIKE" not in sql, "classifier fragments are unsafe next to params"
    out = _emulate(sql, ("__A__",) * 4)
    assert out.count("__ARG") >= 4


def test_report_metric_derives_abandonment_and_excludes_in_flight():
    """Rule 4: abandoned = outcome IS NULL past the threshold, computed in
    the read — and a fresh NULL is in_flight, excluded from the denominator
    (an execution started 30s before the build is not abandoned)."""
    sql = asr._recipe_lifecycle_sql()
    assert "outcome IS NULL" in sql
    assert "make_interval(mins => %s)" in sql
    assert "in_flight" in sql
    for outcome in ("completed", "failed", "abandoned"):
        assert f"'{outcome}'" in sql
    # rule 1 again, at the read layer: nothing in this query touches
    # session_id — the row IS the unit, identity columns are for joins.
    assert "session_id" not in sql


