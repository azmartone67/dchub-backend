def test_offline_build_carries_the_metric_in_execution_quality(monkeypatch):
    """Degraded path: the new block must appear in execution_quality with an
    explicit non-value status — never a silent absence, never an invented 0."""
    monkeypatch.delenv("DATABASE_URL", raising=False)
    monkeypatch.delenv("NEON_DATABASE_URL", raising=False)
    p = asr._build_report()
    eq = next(s for s in p["sections"] if s["section"] == "execution_quality")
    block = eq["metrics"]["recipe_completion_rate"]
    assert block["value"] is None
    assert block["status"] in ("UNAVAILABLE", "UNMEASURED")
    conf = p["confidence"]["recipe_lifecycle_denominator"]
    assert conf["state"] == "unavailable" and conf["why"].strip()
